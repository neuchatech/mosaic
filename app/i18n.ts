export function normalizeMosaicLocale(value?: string | null): MosaicLocale {
  const language = value?.trim().toLowerCase().split(/[-_]/)[0];
  return mosaicLocales.includes(language as MosaicLocale) ? language as MosaicLocale : "en";
}

export function detectMosaicLocale(languages: readonly string[] = []): MosaicLocale {
  for (const language of languages) {
    const normalized = normalizeMosaicLocale(language);
    if (normalized !== "en" || language.toLowerCase().startsWith("en")) return normalized;
  }
  return "en";
}

export function mosaicTranslate(locale: MosaicLocale, key: MosaicMessageKey): string {
  if (locale === "en") return english[key];
  return translations[locale][key] ?? english[key];
}
